/** 未命中告警去重（同一键只告警一次） */
const warned = new Set<string>();
function lookup(map: Record<string, string>, key: string, kind: string): string {
  const hit = map[key];
  if (hit) return hit;
  const tag = `${kind}:${key}`;
  if (!warned.has(tag)) {
    warned.add(tag);
    console.warn(`[spec-i18n] 未收录的中文${kind}，英文版将保留原文: ${key}`);
  }
  return key;
}

/** specs 中文 → 英文（结构与源数据同构；null 透传） */
